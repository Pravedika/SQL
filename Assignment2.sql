CREATE DATABASE MY_DATA;
USE MY_DATA;
CREATE TABLE STUDENTS(
STUDENT_ID INT,
STUDENT_NAME VARCHAR(100),
GENDER VARCHAR(10),
AGE INT,
CITY VARCHAR(50),
COURSE VARCHAR(100),
FEE DECIMAL(10,2),
JOINING_DATE DATE
 );
DESC STUDENTS;
CREATE TABLE EMPLOYEES(
  EMP_ID INT,
  EMP_NAME VARCHAR(100),
  DEPARTMENT VARCHAR(50),
  SALARY DECIMAL(10,2),
  CITY VARCHAR(50),
  JOINING_DATE DATE
  );
DESC EMPLOYEES;
CREATE TABLE ORDERS(
  ORD_ID INT,
    CUSTOMER_NAME VARCHAR(100),
    PRODUCT VARCHAR(100),
    QUANTITY INT,
    PRICE DECIMAL(10,2),
    ORDER_DATE DATE
   );
DESC ORDERS;
